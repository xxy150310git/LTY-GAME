/* 秒数转成 mm:ss */
function formatTime(seconds) {
  const pad = function (v) {
    return v < 10 ? "0" + v : String(v);
  };
  return pad(Math.floor(seconds / 60)) + ":" + pad(seconds % 60);
}

/* 取某首歌的插画 SVG，没登记就用兜底图案 */
function artSvg(song) {
  const art = SONG_ART[song] || DEFAULT_ART;
  return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" '
    + 'stroke-linecap="round" stroke-linejoin="round">' + art.art + "</svg>";
}

/* 从某首歌里挑两句不一样的歌词，做成这一对牌。
   太长会撑破小牌面、太短又认不出是哪首歌，所以优先挑中等长度的句子 */
function pickLyricPair(song) {
  const pool = QUESTIONS.filter(function (item) {
    return item.song === song;
  });

  const picked = [];
  const seen = {};

  function take(keep) {
    for (let i = 0; i < pool.length && picked.length < 2; i++) {
      const key = normalize(pool[i].a);
      if (!key || seen[key] || !keep(key.length)) continue;
      seen[key] = true;
      picked.push(pool[i].a);
    }
  }

  take(function (len) { return len >= 7 && len <= 12; });  /* 最理想：牌面刚好一行到两行 */
  take(function (len) { return len >= 4; });               /* 退一步：别太短就行 */
  take(function (len) { return len > 0; });                /* 再退：能显示就行 */

  /* 兜底：万一这首歌只凑得出一句，两张牌就用同一句（现有题库不会走到这里） */
  while (picked.length < 2) picked.push(picked[0] || song);

  return picked;
}

/* 开局：从已选歌曲里随机挑 8 首（不重复），每首取两句不同的歌词做成两张牌 */
function startMemory() {
  clearTimeout(mem.backTimer);
  stopMemoryTimer();
  stopRushTimer();
  closeCelebrate();
  closeReview();

  /* 8 对需要 8 首不同的歌 */
  if (state.selected.length < MEMORY_PAIRS) return;

  const songs = shuffle(state.selected.slice()).slice(0, MEMORY_PAIRS);
  const cards = [];

  songs.forEach(function (song, i) {
    const lines = pickLyricPair(song);
    cards.push({ song: song, text: lines[0], id: i * 2 });
    cards.push({ song: song, text: lines[1], id: i * 2 + 1 });
  });

  mem.cards = shuffle(cards);
  mem.total = songs.length;
  mem.first = null;
  mem.lock = false;
  mem.moves = 0;
  mem.matched = 0;
  mem.seconds = 0;

  el.memTime.textContent = "用时 00:00";
  el.memMoves.textContent = "步数 0";
  el.memProgress.textContent = "已配对 0 / " + mem.total;
  el.memFeedback.textContent = "";
  el.memFeedback.className = "feedback";

  renderBoard();
  showScreen("memory");
  startMemoryTimer();
}

