/* 生成当天日期，形如 2026-10-03 */
function today() {
  const d = new Date();
  const pad = function (v) {
    return v < 10 ? "0" + v : String(v);
  };
  return d.getFullYear() + "-" + pad(d.getMonth() + 1) + "-" + pad(d.getDate());
}

/* 把已选歌曲的题目排成一份可打印的卷子，再唤起浏览器的"打印／另存为 PDF" */
function exportQuestions() {
  const pool = selectedPool();
  if (pool.length === 0) return;

  const songMode = state.mode === "song";
  const keys = ["A", "B", "C", "D"];
  const answers = [];

  el.printRoot.innerHTML = "";

  const title = document.createElement("h1");
  title.className = "print-title";
  title.textContent = "洛天依接歌词 · 锦依卫特训";
  el.printRoot.appendChild(title);

  const sub = document.createElement("p");
  sub.className = "print-sub";
  sub.textContent = "玩法：" + currentMode().name + "　共 " + pool.length + " 题　生成日期：" + today();
  el.printRoot.appendChild(sub);

  pool.forEach(function (item, i) {
    const options = buildOptions(item);
    const rightIndex = options.indexOf(rightAnswer(item));
    answers.push((i + 1) + "." + keys[rightIndex]);

    const block = document.createElement("div");
    block.className = "print-item";

    const question = document.createElement("div");
    question.className = "print-q";
    /* 题干按当前玩法生成：猜歌名带书名号提示、填空补词带空位、找异句带问法 */
    question.textContent = (i + 1) + ". " + stemOf(item, true);
    block.appendChild(question);

    const optionLine = document.createElement("div");
    optionLine.className = "print-opts";
    optionLine.textContent = options.map(function (value, k) {
      return keys[k] + ". " + (songMode ? "《" + value + "》" : value);
    }).join("　　");
    block.appendChild(optionLine);

    el.printRoot.appendChild(block);
  });

  const answerTitle = document.createElement("h2");
  answerTitle.className = "print-answer-title";
  answerTitle.textContent = "答案";
  el.printRoot.appendChild(answerTitle);

  const answerLine = document.createElement("div");
  answerLine.className = "print-answers";
  answerLine.textContent = answers.join("　");
  el.printRoot.appendChild(answerLine);

  window.print();
}

