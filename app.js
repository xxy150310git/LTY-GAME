/* 键盘：Esc 关弹窗，1 到 4 对应选 A 到 D */
document.addEventListener("keydown", function (event) {
  if (event.key === "Escape") {
    if (!el.user.hidden) {
      closeUser();
      return;
    }
    if (!el.review.hidden) {
      closeReview();
      return;
    }
    if (!el.modal.hidden) {
      closeModal();
      return;
    }
  }
  /* 有弹窗挡着的时候，1~4 不该被当成答题快捷键 */
  if (state.locked || !el.modal.hidden || !el.review.hidden || !el.user.hidden) return;

  const at = ["1", "2", "3", "4"].indexOf(event.key);
  if (at === -1) return;
  const buttons = el.options.querySelectorAll(".option");
  if (buttons[at]) buttons[at].click();
});

