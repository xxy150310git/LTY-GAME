/* ---------- 判分：把两句话都"洗干净"再比 ---------- */

/* 全角字符转半角，例如"Ａ"转"A"、"！"转"!"、"１"转"1" */
function toHalfWidth(text) {
  return text.replace(/[\uFF01-\uFF5E]/g, function (ch) {
    return String.fromCharCode(ch.charCodeAt(0) - 0xFEE0);
  }).replace(/\u3000/g, " ");
}

/* 只保留中文、字母和数字，丢掉空格与中英文标点，并统一小写 */
function normalize(text) {
  return toHalfWidth(String(text || ""))
    .toLowerCase()
    .replace(/[^0-9a-z\u4e00-\u9fff]/g, "");
}

/* 在 normalize 的基础上再把字母数字也丢掉，用来兼容 NaYo、Ayo 这类英文尾缀 */
function normalizeCore(text) {
  return normalize(text).replace(/[0-9a-z]/g, "");
}

/* 编辑距离，用滚动数组把空间压到一维 */
function levenshtein(a, b) {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;

  let prev = new Array(b.length + 1);
  let curr = new Array(b.length + 1);

  for (let j = 0; j <= b.length; j++) prev[j] = j;

  for (let i = 1; i <= a.length; i++) {
    curr[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const cost = a.charCodeAt(i - 1) === b.charCodeAt(j - 1) ? 0 : 1;
      curr[j] = Math.min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost);
    }
    const tmp = prev;
    prev = curr;
    curr = tmp;
  }
  return prev[b.length];
}

/* 相似度：0 到 1，1 表示完全一样 */
function similarity(a, b) {
  const len = Math.max(a.length, b.length);
  if (len === 0) return 1;
  return 1 - levenshtein(a, b) / len;
}

/* 把字符串切成相邻两字一组，用集合存起来 */
function bigramSet(text) {
  const set = new Set();
  for (let i = 0; i + 1 < text.length; i++) {
    set.add(text.slice(i, i + 2));
  }
  return set;
}

/* 关键词覆盖率：标准答案里的相邻两字词组，有多少比例出现在玩家的作答里 */
function coverage(target, answer) {
  const targetSet = bigramSet(target);
  if (targetSet.size === 0) return target === answer ? 1 : 0;
  const answerSet = bigramSet(answer);
  let hit = 0;
  targetSet.forEach(function (gram) {
    if (answerSet.has(gram)) hit++;
  });
  return hit / targetSet.size;
}

/* 判分主函数：返回 true 表示这一句接上了 */
function isCorrect(input, target) {
  const user = normalize(input);
  const key = normalize(target);
  if (!user) return false;

  /* 完全一致（已忽略空格与中英文标点差异） */
  if (user === key) return true;

  /* 差别只在英文尾缀时也算对，例如只写"会是她吗"对上"会是她吗NaYo" */
  const userCore = normalizeCore(input);
  const keyCore = normalizeCore(target);
  if (userCore && userCore === keyCore) return true;

  const shortLen = Math.min(user.length, key.length);
  const longLen = Math.max(user.length, key.length);

  /* 一方是另一方的子串，且长度差距不大，算接上了 */
  if (shortLen / longLen >= 0.7 && (key.indexOf(user) > -1 || user.indexOf(key) > -1)) {
    return true;
  }

  /* 长度差太多说明不是同一句，直接判错，避免误给分 */
  if (shortLen / longLen < 0.55) return false;

  /* 允许少量错字 */
  if (similarity(user, key) >= 0.82) return true;

  /* 核心词基本都对上 */
  if (coverage(key, user) >= 0.9) return true;

  return false;
}

