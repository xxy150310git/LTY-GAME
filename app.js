/* 把已勾选那几首歌依次排出来：小插画 + 歌名 + 这首歌的全部歌词 */
function renderReview() {
  const songs = state.selected.slice();

  el.reviewTitle.textContent = "复习依下";
  el.reviewList.innerHTML = "";
  el.reviewJump.innerHTML = "";

  /* 勾的歌多了就得靠跳转条，不然要滚半天 */
  const needJump = songs.length > REVIEW_JUMP_MIN;

  if (songs.length === 0) {
    el.reviewSub.textContent = "还没选歌，先去「歌曲库」勾几首吧～";
    el.reviewJump.hidden = true;
    return;
  }

  let lineCount = 0;
  const anchors = [];

  songs.forEach(function (song) {
    const look = SONG_ART[song] || DEFAULT_ART;

    const block = document.createElement("section");
    block.className = "review-song";

    const head = document.createElement("div");
    head.className = "review-head";

    const art = document.createElement("span");
    art.className = "review-art";
    art.style.background = look.bg;
    art.innerHTML = artSvg(song);

    const name = document.createElement("h3");
    name.className = "review-name";
    name.textContent = "《" + song + "》";

    head.appendChild(art);
    head.appendChild(name);
    block.appendChild(head);

    const lines = document.createElement("div");
    lines.className = "review-lines";

    /* 题库里每条都是「相连的两句」（q 是上半句、a 是下半句），
       而且相邻两条会重叠一句：上一条的 a 常常就是下一条的 q。
       所以这里要把 q、a 两句都按顺序铺开，全首出现过的句子只列一次 ——
       只取 a 的话等于每两句丢掉一句，歌词单就会中间缺句子。 */
    const seen = {};
    QUESTIONS.forEach(function (item) {
      if (item.song !== song) return;

      [item.q, item.a].forEach(function (text) {
        const key = normalize(text);
        if (!key || seen[key]) return;
        seen[key] = true;
        lineCount++;

        const line = document.createElement("span");
        line.className = "review-line";
        line.textContent = text;
        lines.appendChild(line);
      });
    });

    block.appendChild(lines);
    el.reviewList.appendChild(block);

    if (needJump) anchors.push({ song: song, block: block });
  });

  el.reviewSub.textContent = "已选 " + songs.length + " 首 · 共 " + lineCount + " 句歌词";

  el.reviewJump.hidden = !needJump;

  if (!needJump) return;

  anchors.forEach(function (anchor) {
    const chip = document.createElement("button");
    chip.type = "button";
    chip.className = "review-jump-chip";
    chip.textContent = anchor.song;
    chip.addEventListener("click", function () {
      /* 用两块的真实位置算差值，不依赖 offsetParent 是谁 */
      el.reviewList.scrollTop += anchor.block.getBoundingClientRect().top
        - el.reviewList.getBoundingClientRect().top;

      const all = el.reviewJump.querySelectorAll(".review-jump-chip");
      for (let i = 0; i < all.length; i++) {
        all[i].classList.toggle("is-on", all[i] === chip);
      }
    });
    el.reviewJump.appendChild(chip);
  });
}

